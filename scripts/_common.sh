#!/bin/bash

#=================================================
# COMMON VARIABLES AND CUSTOM HELPERS
#=================================================

# Files shared by all Newt instances (real client IPs + fail2ban)
NEWT_NGINX_REALIP=/etc/nginx/conf.d/newt-realip.conf
NEWT_NGINX_BANNED=/etc/nginx/newt-banned-ips.conf
NEWT_F2B_ACTION=/etc/fail2ban/action.d/newt-nginx-deny.conf
NEWT_F2B_JAIL=/etc/fail2ban/jail.d/newt-realip.conf

_newt_service_add() {
    yunohost service add "$app" \
        --description="Newt - Pangolin site connector" \
        --log="/var/log/$app/$app.log"
}

# Deploy the binary and env file with tight permissions:
# root owns everything, the app user can only read/execute.
_newt_fix_permissions() {
    chown root:"$app" "$install_dir"
    chmod 750 "$install_dir"
    local file
    for file in newt newt.env blueprint.yaml; do
        [[ -e "$install_dir/$file" ]] || continue
        chown root:"$app" "$install_dir/$file"
        chmod 640 "$install_dir/$file"
    done
    chmod 750 "$install_dir/newt"
}

# Pangolin endpoint: http(s)://host[/path]
_newt_endpoint_is_valid() {
    [[ "$1" =~ ^https?://[^[:space:]/]+(/[^[:space:]]*)?$ ]]
}

# Pangolin Cloud only works with its cloud exit nodes, which NO_CLOUD filters out
_newt_is_pangolin_cloud() {
    local host="${pangolin_endpoint#*://}"
    host="${host%%/*}"
    host="${host%%:*}"
    [[ "$host" == "pangolin.net" || "$host" == *.pangolin.net ]]
}

# All YunoHost domains, one per line
_newt_yunohost_domains() {
    yunohost domain list --output-as json \
        | python3 -c 'import json, sys; print("\n".join(json.load(sys.stdin)["domains"]))'
}

# Comma-separated setting -> one domain per line
_newt_published_domains() {
    tr ',' '\n' <<< "${published_domains:-}" | sed '/^\s*$/d; s/^\s*//; s/\s*$//'
}

# Pangolin resources for the published domains: one HTTP resource per
# domain, targeting YunoHost's NGINX through the tunnel. Host header and
# SNI are set to the domain so NGINX picks the right vhost.
_newt_write_blueprint() {
    local file="$install_dir/blueprint.yaml"
    blueprint_file=""
    if [[ -z "$(_newt_published_domains)" ]]; then
        ynh_safe_rm "$file"
        return
    fi
    local sso=false
    [[ "${pangolin_sso:-0}" == "1" ]] && sso=true
    local domain
    {
        echo "# Generated by YunoHost from the $app settings, manual edits are overwritten"
        echo "public-resources:"
        while read -r domain; do
            cat << EOF
  ynh-${domain//./-}:
    name: "$domain (YunoHost)"
    mode: http
    full-domain: "$domain"
    host-header: "$domain"
    tls-server-name: "$domain"
    auth:
      sso-enabled: $sso
    targets:
      - hostname: 127.0.0.1
        port: 443
        method: https
EOF
        done < <(_newt_published_domains)
    } > "$file"
    blueprint_file="$file"
}

_newt_add_config() {
    if _newt_is_pangolin_cloud; then
        no_cloud=false
    else
        no_cloud=true
    fi
    _newt_write_blueprint
    ynh_config_add --template="newt.env" --destination="$install_dir/newt.env"
}

# Real client IPs (nginx real_ip) + fail2ban bans in nginx. These files
# are shared: they stay as long as one Newt instance (other than $1, the
# instance being removed) has real_ip enabled.
_newt_sync_realip() {
    local exclude="${1:-}"
    local wanted=false
    local settings instance
    for settings in /etc/yunohost/apps/newt/settings.yml /etc/yunohost/apps/newt__*/settings.yml; do
        [[ -f "$settings" ]] || continue
        instance="$(basename "$(dirname "$settings")")"
        [[ "$instance" == "$exclude" ]] && continue
        if [[ "$(ynh_app_setting_get --app="$instance" --key=real_ip)" == "1" ]]; then
            wanted=true
        fi
    done

    if [[ "$wanted" == true ]]; then
        [[ -f "$NEWT_NGINX_BANNED" ]] || touch "$NEWT_NGINX_BANNED"
        install -m 644 "$YNH_APP_BASEDIR/conf/nginx-realip.conf" "$NEWT_NGINX_REALIP"
        install -m 644 "$YNH_APP_BASEDIR/conf/fail2ban-action.conf" "$NEWT_F2B_ACTION"
        install -m 644 "$YNH_APP_BASEDIR/conf/fail2ban-jail.conf" "$NEWT_F2B_JAIL"
    else
        ynh_safe_rm "$NEWT_NGINX_REALIP"
        ynh_safe_rm "$NEWT_F2B_JAIL"
        ynh_safe_rm "$NEWT_F2B_ACTION"
        ynh_safe_rm "$NEWT_NGINX_BANNED"
    fi

    nginx -t 2>/dev/null || ynh_die "The nginx configuration is broken, see 'nginx -t'"
    ynh_systemctl --service=nginx --action=reload
    ynh_systemctl --service=fail2ban --action=restart
}

# YunoHost's diagnosis checks DNS records, HTTP reachability and open
# ports against the server's own public IP. Behind Pangolin these checks
# fail by design, so ignore them for the published domains (and ports
# 80/443 once every public domain goes through Pangolin). The filters
# added are stored so they can be removed exactly.
# (Written directly: 'yunohost diagnosis ignore' only accepts filters
# for issues present in the last diagnosis report.)
_newt_sync_diagnosis() {
    local remove_only="${1:-false}"
    local -a filters=()

    if [[ "$remove_only" != true && "${diagnosis_ignore:-0}" == "1" ]]; then
        local domain all_public_published=true has_published=false
        while read -r domain; do
            filters+=("dnsrecords domain=$domain category=basic" "web domain=$domain")
            has_published=true
        done < <(_newt_published_domains)

        while read -r domain; do
            case "$domain" in
                *.home.arpa | *.internal | *.local | *.localhost | *.onion | *.test) continue ;;
            esac
            _newt_published_domains | grep -qxF "$domain" || all_public_published=false
        done < <(_newt_yunohost_domains)

        if [[ "$has_published" == true && "$all_public_published" == true ]]; then
            filters+=("ports port=80" "ports port=443")
        fi
    fi

    local new_filters
    new_filters="$(IFS=';'; echo "${filters[*]}")"
    python3 - "$(ynh_app_setting_get --key=diagnosis_ignored)" "$new_filters" << 'EOF'
import sys
from yunohost.diagnosis import _diagnosis_read_configuration, _diagnosis_write_configuration

def parse(spec):
    category, *criterias = spec.split()
    return category, dict(c.split("=", 1) for c in criterias)

old, new = ([f for f in arg.split(";") if f.strip()] for arg in sys.argv[1:3])
conf = _diagnosis_read_configuration() or {}
ignore_filters = conf.setdefault("ignore_filters", {})
for spec in old:
    category, criterias = parse(spec)
    if criterias in ignore_filters.get(category, []):
        ignore_filters[category].remove(criterias)
for spec in new:
    category, criterias = parse(spec)
    if criterias not in ignore_filters.setdefault(category, []):
        ignore_filters[category].append(criterias)
conf["ignore_filters"] = {k: v for k, v in ignore_filters.items() if v}
_diagnosis_write_configuration(conf)
EOF
    ynh_app_setting_set --key=diagnosis_ignored --value="$new_filters"
}

# Start the service and make sure it is not crash-looping.
# (Newt runs forever and retries the connection on its own, so a
# running process is the right success criterion here.)
_newt_start() {
    ynh_systemctl --service="$app" --action="start"
    sleep 5
    if ! systemctl is-active --quiet "$app"; then
        journalctl --quiet --no-hostname --no-pager --lines=30 --unit="$app" >&2 || true
        tail --lines=30 "/var/log/$app/$app.log" >&2 || true
        ynh_die "The $app service failed to start, see the log above"
    fi
}
